export type MessageKey = keyof Dict;
export type Translate = (key: MessageKey, vars?: Record<string, string | number>) => string;

export function resolveLanguage(value: unknown, fallback: Language = 'az'): Language {
  return typeof value === 'string' && (LANGUAGES as readonly string[]).includes(value) ? (value as Language) : fallback;
}

export function translator(lang: Language): Translate {
  const dict = DICTS[lang];
  return (key, vars) => {
    let s = dict[key] ?? en[key];
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.split(`{${k}}`).join(String(v));
    return s;
  };
}

export function declineMessage(lang: Language, code: DeclineCode | null): string {
  return code ? DECLINES[lang][code] : '';
}

